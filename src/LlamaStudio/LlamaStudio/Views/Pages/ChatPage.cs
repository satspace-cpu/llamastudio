	private void SessionItemPointerReleased(object? sender, PointerReleasedEventArgs e)
	{
		if (_dragSourcePanel != null)
		{
			_dragSourcePanel.RemoveHandler(InputElement.PointerMovedEvent, SessionItemPointerMoved);
			_dragSourcePanel.RemoveHandler(InputElement.PointerReleasedEvent, SessionItemPointerReleased);
		}
		if (!_isDragging || _draggedSession == null || _viewModel == null)
		{
			if (_dragSourcePanel != null)
			{
				_dragSourcePanel.Opacity = 1.0;
			}
			_draggedSession = null;
			_dragSourcePanel = null;
			_isDragging = false;
			return;
		}
		if (_dragSourcePanel != null)
		{
			_dragSourcePanel.Opacity = 1.0;
		}
		ChatSession sessionUnderPointer = GetSessionUnderPointer(e);
		if (sessionUnderPointer == null)
		{
			_draggedSession = null;
			_dragSourcePanel = null;
			_isDragging = false;
			return;
		}
		List<ChatSession> sessionsList = _viewModel.Sessions.ToList();
		int draggedIndex = sessionsList.IndexOf(_draggedSession);
		int targetIndex = sessionsList.IndexOf(sessionUnderPointer);
		if (draggedIndex >= 0 && targetIndex >= 0 && draggedIndex != targetIndex)
		{
			sessionsList.RemoveAt(draggedIndex);
			sessionsList.Insert(targetIndex, _draggedSession);
			foreach (ChatSession session in _viewModel.Sessions)
			{
				_viewModel.Sessions.Remove(session);
			}
			foreach (ChatSession item in sessionsList)
			{
				_viewModel.Sessions.Add(item);
			}
			_viewModel.ReorderSessionsCommand?.Execute(null);
		}
		_draggedSession = null;
		_dragSourcePanel = null;
		_isDragging = false;
	}

